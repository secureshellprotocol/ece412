import numpy as np
import librosa

class ColoredNoiseFilter:
    """
    A class to generate colored noise or apply a spectral coloring filter
    to an existing signal using frequency-domain shaping.

    The color is determined by the spectral slope (alpha), where
    Power Spectral Density S(f) ~ 1 / f^alpha.

    generated by gemma stone on chatterbox.ee
    """

    def __init__(self, spectral_slope: float = 1.0):
        """
        Args:
            spectral_slope (float): The power-law exponent (alpha).
                0.0: White noise (flat spectrum)
                1.0: Pink noise (1/f spectrum)
                2.0: Brown/Red noise (1/f^2 spectrum)
        """
        self.alpha = spectral_slope

    def _get_scaling_filter(self, n_samples: int, sr: int) -> np.ndarray:
        """Generates the frequency-domain scaling coefficients."""
        # Generate frequencies corresponding to the FFT bins
        freqs = np.fft.rfftfreq(n_samples, d=1/sr)

        # Avoid division by zero at the 0Hz (DC) component.
        # We set the DC component to match the first non-zero bin.
        if len(freqs) > 1:
            freqs[0] = freqs[1]
        else:
            freqs[0] = 1e-9

        # For Power Density S(f) ~ f^-alpha,
        # the Amplitude Spectrum A(f) ~ f^(-alpha/2)
        scaling = freqs ** (-self.alpha / 2.0)
        return scaling

    def apply(
        self,
        signal: np.ndarray,
        sr: int = 22050,
        attenuation: float = 1.0
    ) -> np.ndarray:
        """
        Colors an existing signal by applying the spectral slope.

        Args:
            signal (np.ndarray): The input audio signal.
            sr (int): Sampling rate of the input signal.

        Returns:
            np.ndarray: The filtered/colored signal.
        """
        n_samples = len(signal)

        # 1. Transform signal to frequency domain
        fft_signal = np.fft.rfft(signal)

        # 2. Apply spectral shaping
        scaling = self._get_scaling_filter(n_samples, sr)
        fft_colored = fft_signal * scaling * attenuation

        # 3. Transform back to time domain
        colored_signal = np.fft.irfft(fft_colored, n=n_samples)

        # 4. Re-normalize to original peak amplitude
        original_peak = np.max(np.abs(signal))
        if np.max(np.abs(colored_signal)) > 0:
            colored_signal *= (original_peak / np.max(np.abs(colored_signal)))

        return colored_signal

